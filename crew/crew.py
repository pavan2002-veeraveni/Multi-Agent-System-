"""
MarketResearchCrew – Hierarchical Crew Orchestrator

Assembles the agents, tasks, and benchmarking into a single runnable
Crew configured with Process.hierarchical and a manager LLM.
"""

import os
import logging
from crewai import Crew, Process
from crew.agents import create_agents
from crew.tasks import create_tasks
from crew.benchmarks import BenchmarkTracker

logger = logging.getLogger(__name__)


class MarketResearchCrew:
    """
    Orchestrates a hierarchical CrewAI team consisting of a Researcher,
    Analyst, and Writer, all managed by a supervisor LLM.
    """

    def __init__(
        self,
        query: str,
        csv_path: str = "data/sample_metrics.csv",
        manager_model: str | None = None,
        benchmark_path: str = "benchmarks.json",
    ):
        self.query = query
        self.csv_path = csv_path
        self.manager_model = manager_model or os.getenv("MANAGER_LLM_MODEL", "gpt-4o")
        self.benchmark_path = benchmark_path
        self.tracker = BenchmarkTracker(output_path=benchmark_path)

        # Build agents and tasks
        self.agents_map = create_agents()
        self.agents = list(self.agents_map.values())
        self.tasks = create_tasks(query=query, csv_path=csv_path)

        # Assemble the hierarchical crew
        self.crew = Crew(
            agents=self.agents,
            tasks=self.tasks,
            process=Process.hierarchical,
            manager_llm=self.manager_model,
            verbose=True,
            task_callback=self.tracker.task_callback,
        )

        logger.info(
            "MarketResearchCrew initialized — manager=%s, agents=%d, tasks=%d",
            self.manager_model,
            len(self.agents),
            len(self.tasks),
        )

    def run(self) -> str:
        """
        Execute the full hierarchical pipeline.

        Returns:
            The final report text generated by the crew.
        """
        logger.info("=" * 60)
        logger.info("Starting MarketResearchCrew for: '%s'", self.query)
        logger.info("=" * 60)

        # Start benchmarking
        self.tracker.start_pipeline()
        self.tracker.start_task("research")
        self.tracker.start_task("analysis")
        self.tracker.start_task("report_writing")

        try:
            # Kick off the hierarchical crew
            result = self.crew.kickoff()

            # Extract string result
            if hasattr(result, "raw"):
                report_text = result.raw
            else:
                report_text = str(result)

            logger.info("Crew execution completed successfully.")

        except Exception as exc:
            logger.error("Crew execution failed: %s", exc)
            self.tracker.stop_task("research", status="error")
            self.tracker.stop_task("analysis", status="error")
            self.tracker.stop_task("report_writing", status="error")
            raise

        finally:
            # Stop any remaining active timers
            for task_name in list(self.tracker._active_timers.keys()):
                self.tracker.stop_task(task_name)

            self.tracker.stop_pipeline()
            self.tracker.save(self.benchmark_path)
            logger.info("Benchmarks saved to %s", self.benchmark_path)

        return report_text
